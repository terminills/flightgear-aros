/* Decodes a small .xz stream (LZMA2, CRC64) the way SimGear's archive extractor does and prints what liblzma
   answers. Built twice: xzcheck with the port's liblzma, xzchecksys with the lzma.library of AROS. */
#include <lzma.h>
#include <stdio.h>
#include <string.h>

static const unsigned char xz[] = {
  0xfd, 0x37, 0x7a, 0x58, 0x5a, 0x00, 0x00, 0x04, 0xe6, 0xd6, 0xb4, 0x46,
  0x04, 0xc0, 0x3c, 0x38, 0x21, 0x01, 0x1c, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0xfe, 0x4e, 0x27, 0x1f, 0x01, 0x00, 0x37, 0x46,
  0x6c, 0x69, 0x67, 0x68, 0x74, 0x47, 0x65, 0x61, 0x72, 0x20, 0x66, 0x6f,
  0x72, 0x20, 0x41, 0x52, 0x4f, 0x53, 0x3a, 0x20, 0x61, 0x6e, 0x20, 0x2e,
  0x78, 0x7a, 0x20, 0x73, 0x74, 0x72, 0x65, 0x61, 0x6d, 0x20, 0x77, 0x69,
  0x74, 0x68, 0x20, 0x4c, 0x5a, 0x4d, 0x41, 0x32, 0x20, 0x61, 0x6e, 0x64,
  0x20, 0x43, 0x52, 0x43, 0x36, 0x34, 0x0a, 0x00, 0xc3, 0x7b, 0x26, 0xda,
  0x2b, 0x25, 0x67, 0xf7, 0x00, 0x01, 0x58, 0x38, 0xe9, 0xda, 0xe6, 0x7a,
  0x1f, 0xb6, 0xf3, 0x7d, 0x01, 0x00, 0x00, 0x00, 0x00, 0x04, 0x59, 0x5a
};

int main(void)
{
    lzma_stream s = LZMA_STREAM_INIT;
    unsigned char out[256];
    lzma_ret r;

    printf("xzcheck: liblzma %s, check CRC32 %d CRC64 %d SHA256 %d, filter LZMA2 decoder %d\n",
           lzma_version_string(), lzma_check_is_supported(LZMA_CHECK_CRC32),
           lzma_check_is_supported(LZMA_CHECK_CRC64), lzma_check_is_supported(LZMA_CHECK_SHA256),
           lzma_filter_decoder_is_supported(LZMA_FILTER_LZMA2));
    r = lzma_stream_decoder(&s, UINT64_MAX, LZMA_TELL_ANY_CHECK);
    printf("xzcheck: lzma_stream_decoder %d\n", (int)r);
    if (r != LZMA_OK)
        return 20;
    s.next_in = xz;
    s.avail_in = sizeof(xz);
    do {
        s.next_out = out;
        s.avail_out = sizeof(out) - 1;
        r = lzma_code(&s, LZMA_RUN);
        printf("xzcheck: lzma_code %d, %d bytes out\n", (int)r, (int)(sizeof(out) - 1 - s.avail_out));
    } while (r == LZMA_OK || r == LZMA_GET_CHECK);
    out[sizeof(out) - 1 - s.avail_out] = 0;
    lzma_end(&s);
    if (r != LZMA_STREAM_END) {
        printf("xzcheck: FAILED (%d)\n", (int)r);
        return 20;
    }
    printf("xzcheck: ok: %s", out);
    return 0;
}
